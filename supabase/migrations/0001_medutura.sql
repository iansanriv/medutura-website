create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text not null default '',
  category text not null default 'Accesorios',
  price_cents integer not null check (price_cents > 0),
  inventory integer not null default 0 check (inventory >= 0),
  active boolean not null default true,
  featured boolean not null default false,
  image_key text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  delivery_method text not null check (delivery_method in ('shipping', 'pickup')),
  address text,
  payment_method text not null check (payment_method in ('card', 'paypal', 'ath')),
  payment_status text not null default 'pending' check (payment_status in ('pending', 'paid', 'refunded', 'cancelled')),
  fulfillment_status text not null default 'new' check (fulfillment_status in ('new', 'making', 'ready', 'shipped', 'complete', 'cancelled')),
  subtotal_cents integer not null default 0,
  shipping_cents integer not null default 0,
  tax_cents integer not null default 0,
  total_cents integer not null default 0,
  processor_reference text,
  notes text,
  inventory_reserved boolean not null default true,
  confirmation_sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price_cents integer not null check (unit_price_cents > 0)
);

create table if not exists public.admins (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  email text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists admins_email_lower_unique on public.admins (lower(email));
create index if not exists products_storefront_idx on public.products (active, featured desc, created_at desc);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_processor_reference_idx on public.orders (processor_reference);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.admins enable row level security;

