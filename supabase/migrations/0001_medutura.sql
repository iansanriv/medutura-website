create or replace function public.create_store_order(
  p_customer_name text,
  p_customer_email text,
  p_customer_phone text,
  p_delivery_method text,
  p_address text,
  p_payment_method text,
  p_notes text,
  p_items jsonb,
  p_shipping_cents integer default 0,
  p_tax_rate numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_order_number text := 'MED-' || to_char(now() at time zone 'utc', 'YYYY') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_subtotal integer := 0;
  v_shipping integer := greatest(coalesce(p_shipping_cents, 0), 0);
  v_tax integer;
  v_total integer;
  v_items jsonb;
begin
  if nullif(trim(p_customer_name), '') is null or position('@' in p_customer_email) < 2 or nullif(trim(p_customer_phone), '') is null then
    raise exception 'Completa tu información de contacto.';
  end if;
  if p_delivery_method not in ('shipping', 'pickup') or p_payment_method not in ('card', 'paypal', 'ath') then
    raise exception 'La entrega o el método de pago no es válido.';
  end if;
  if p_tax_rate < 0 or p_tax_rate > 1 then
    raise exception 'La tasa de impuesto configurada no es válida.';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío.';
  end if;
  if p_delivery_method = 'pickup' then
    v_shipping := 0;
  end if;

  insert into public.orders (
    id, order_number, customer_name, customer_email, customer_phone,
    delivery_method, address, payment_method, notes
  ) values (
    v_order_id, v_order_number, trim(p_customer_name), lower(trim(p_customer_email)), trim(p_customer_phone),
    p_delivery_method, nullif(trim(p_address), ''), p_payment_method, nullif(trim(p_notes), '')
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := greatest(coalesce((v_item->>'quantity')::integer, 0), 0);
    if v_quantity < 1 or v_quantity > 20 then
      raise exception 'Una cantidad del carrito no es válida.';
    end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint and active = true
    for update;

    if not found then
      raise exception 'Una de las piezas ya no está disponible.';
    end if;
    if v_product.inventory < v_quantity then
      raise exception 'No queda suficiente inventario de %.', v_product.name;
    end if;

    update public.products
    set inventory = inventory - v_quantity, updated_at = now()
    where id = v_product.id;

    insert into public.order_items (order_id, product_id, product_name, quantity, unit_price_cents)
    values (v_order_id, v_product.id, v_product.name, v_quantity, v_product.price_cents);

    v_subtotal := v_subtotal + (v_product.price_cents * v_quantity);
  end loop;

  v_tax := round(v_subtotal * p_tax_rate)::integer;
  v_total := v_subtotal + v_shipping + v_tax;

  update public.orders
  set subtotal_cents = v_subtotal,
      shipping_cents = v_shipping,
      tax_cents = v_tax,
      total_cents = v_total,
      updated_at = now()
  where id = v_order_id;

  select jsonb_agg(jsonb_build_object(
    'product_id', product_id,
    'name', product_name,
    'quantity', quantity,
    'unit_price_cents', unit_price_cents
  ) order by id)
  into v_items
  from public.order_items
  where order_id = v_order_id;

  return jsonb_build_object(
    'id', v_order_id,
    'order_number', v_order_number,
    'subtotal_cents', v_subtotal,
    'shipping_cents', v_shipping,
    'tax_cents', v_tax,
    'total_cents', v_total,
    'items', coalesce(v_items, '[]'::jsonb)
  );
end;
$$;

create or replace function public.cancel_store_order(p_order_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item record;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or v_order.payment_status <> 'pending' then
    return false;
  end if;

  if v_order.inventory_reserved then
    for v_item in select product_id, quantity from public.order_items where order_id = p_order_id
    loop
      update public.products
      set inventory = inventory + v_item.quantity, updated_at = now()
      where id = v_item.product_id;
    end loop;
  end if;

  update public.orders
  set payment_status = 'cancelled', fulfillment_status = 'cancelled', inventory_reserved = false, updated_at = now()
  where id = p_order_id;
  return true;
end;
$$;

create or replace function public.mark_store_order_paid(p_order_id uuid, p_processor_reference text default null)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
begin
  select payment_status into v_status from public.orders where id = p_order_id for update;
  if not found or v_status = 'cancelled' then
    return false;
  end if;
  update public.orders
  set payment_status = 'paid',
      inventory_reserved = false,
      processor_reference = coalesce(p_processor_reference, processor_reference),
      updated_at = now()
  where id = p_order_id;
  return true;
end;
$$;

revoke all on function public.create_store_order(text, text, text, text, text, text, text, jsonb, integer, numeric) from public;
revoke all on function public.cancel_store_order(uuid) from public;
revoke all on function public.mark_store_order_paid(uuid, text) from public;
grant execute on function public.create_store_order(text, text, text, text, text, text, text, jsonb, integer, numeric) to service_role;
grant execute on function public.cancel_store_order(uuid) to service_role;
grant execute on function public.mark_store_order_paid(uuid, text) to service_role;
